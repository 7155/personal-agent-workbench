export function listMLTemplates() { return Object.entries(TEMPLATES).map(([id, value]) => ({ id, title: value.title, description: value.description, required: value.required })); }
export function mlTemplate(id) { if (!TEMPLATES[id]) throw new Error(`Unknown Earth ML workflow: ${id}`); return { id, ...TEMPLATES[id] }; }
export function prepareMLScript(root, { workflow, saveAs = 'ml-analysis.js', replacements = {} }) {
  const template = mlTemplate(workflow);
  if (typeof saveAs !== 'string' || saveAs.startsWith('/') || saveAs.includes('..') || !saveAs.endsWith('.js')) throw new Error('ML script must be a workspace-relative .js path.');
  const target = path.resolve(root, saveAs);
  if (!target.startsWith(`${path.resolve(root)}${path.sep}`)) throw new Error('ML script escaped the bound workspace.');
  if (fs.existsSync(target) && fs.lstatSync(target).isSymbolicLink()) throw new Error('ML script cannot overwrite a symlink.');
  let script = template.script;
  for (const [key, value] of Object.entries(replacements || {})) {
    if (typeof key !== 'string' || typeof value !== 'string') throw new Error('ML replacements must be string values.');
    script = script.split(key).join(value);
  }
  const unresolved = [...new Set(script.match(/\b(?:DATASET_ID|TRAINING_ASSET|CLASS_PROPERTY|BANDS|SCALE|REGION|BEFORE_DATASET|AFTER_DATASET|NUM_CLUSTERS)\b/g) || [])];
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, script, { mode: 0o600 });
  return { workflow, path: path.relative(root, target), unresolved, bytes: Buffer.byteLength(script), script };
}
