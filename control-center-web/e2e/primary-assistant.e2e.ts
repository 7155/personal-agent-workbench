import { expect, test } from '@playwright/test';
import { coordinatorControls, createControlledSession, expectNoHorizontalPageOverflow } from './helpers';

test('the persistent assistant explicitly creates a scoped object without starting its task', async ({page})=>{
  await page.goto('/?controlTransport=mock#/agent-controller');
  const app=page.locator('.paw-window-shell[data-app="agent-controller"]');
  const composer=app.getByRole('textbox',{name:'消息',exact:true});
  await expect(composer).toBeVisible();
  const draft='先讨论目标，创建并不发送这段草稿';await composer.fill(draft);
  const target=await createControlledSession(page,'检查独立控制对象');
  await expect(target).toContainText('Session · 就绪');
  await target.click();
  const session=page.locator('.paw-window-shell[data-window-target="session"]');
  await expect(session.getByRole('textbox',{name:'消息',exact:true})).toHaveValue('');
  await expect(session.locator('.paw-user-message')).toHaveCount(0);
  await expect(session.getByRole('button',{name:/^发送/})).toBeDisabled();
  await page.evaluate(()=>{location.hash='#/agent-controller';});
  await expect(composer).toHaveValue(draft);
  await expect(app.locator('.paw-user-message, .agent-user-message, .ccui-user-text',{hasText:draft})).toHaveCount(0);
  await expectNoHorizontalPageOverflow(page);
});

test('the primary conversation carries a route draft without sending it',async({page})=>{
  const draft='先带入草稿，确认后再发送';
  await page.goto('/?controlTransport=mock#/agent?draft='+encodeURIComponent(draft));
  const home=page.getByRole('textbox',{name:'描述你想完成的工作'});
  await expect(home).toHaveValue(draft);
  await expect(page.locator('.paw-user-message',{hasText:draft})).toHaveCount(0);
  await page.evaluate(()=>{location.hash='#/memory';});
  await expect(page.locator('.paw-window-shell[data-app="memory"]')).toBeVisible();
  await page.evaluate(()=>{location.hash='#/agent';});
  await expect(home).toHaveValue(draft);
  await expect(page.locator('.paw-user-message',{hasText:draft})).toHaveCount(0);
});

test('StarMate discusses, delegates, stops, returns to work and edits the sourced profile',async({page},info)=>{
  test.setTimeout(90_000);
  await page.goto('/?controlTransport=mock#/agent-controller');
  const app=page.locator('.paw-window-shell[data-app="agent-controller"]');
  const composer=app.getByRole('textbox',{name:'消息',exact:true});
  await expect(composer).toBeVisible();
  await expect(app.getByRole('heading',{name:'星伴',exact:true})).toBeVisible();
  await expect(app.getByText('持续对话',{exact:false}).first()).toBeVisible();
  await expectNoHorizontalPageOverflow(page);
  await info.attach('starmate-home.png',{body:await page.screenshot(),contentType:'image/png'});
  const discussion='先帮我想清楚这个项目的目标';await composer.fill(discussion);
  await app.getByRole('button',{name:'发送',exact:true}).click();
  await expect(app.locator('.paw-user-message, .agent-user-message, .ccui-user-text',{hasText:discussion})).toHaveCount(1);
  await expect(app.getByText('我们可以先把目标和顾虑说清楚。',{exact:false})).toBeVisible();
  const task='检查工作台的对话入口';const target=await createControlledSession(page,task);
  await expect(target).toContainText('Session · 就绪');await target.click();
  const session=page.locator('.paw-window-shell[data-window-target="session"]');
  const input=session.getByRole('textbox',{name:'消息',exact:true});
  await expect(input).toBeVisible();await expect(session.locator('.paw-user-message')).toHaveCount(0);
  await input.fill(task);await session.getByRole('button',{name:'发送',exact:true}).click();
  await expect(session.locator('.paw-user-message',{hasText:task})).toHaveCount(1);
  const stop=session.getByRole('button',{name:'停止本轮',exact:true});await expect(stop).toBeVisible();await stop.click();
  await expect(stop).toBeHidden();await page.waitForTimeout(4200);
  await expect(session.getByText('这是演示任务的结果：',{exact:false})).toHaveCount(0);
  await info.attach('starmate-target-stopped.png',{body:await page.screenshot(),contentType:'image/png'});
  await page.evaluate(()=>{location.hash='#/agent-controller';});
  await coordinatorControls(page);await expect(target).toContainText('已停止');await target.click();
  await input.fill('继续检查，给我结果');await session.getByRole('button',{name:'发送',exact:true}).click();
  await expect(session.getByTestId('virtuoso-item-list').getByText('这是演示任务的结果：',{exact:false})).toBeVisible({timeout:10000});
  await info.attach('starmate-target-result.png',{body:await page.screenshot(),contentType:'image/png'});
  await page.evaluate(()=>{location.hash='#/agent-controller';});
  await coordinatorControls(page);await expect(target).toContainText('已完成');
  const railClose=app.getByRole('button',{name:'收起控制面板'});if(await railClose.isVisible())await railClose.click();
  await app.getByRole('button',{name:'管理长期记忆',exact:true}).click();
  const memory=page.locator('.paw-window-shell[data-app="memory"]');
  await memory.getByRole('button',{name:'关于我',exact:true}).click();
  const paragraph=memory.getByRole('textbox',{name:'个人背景 1'});
  await expect(paragraph).toHaveValue('我在做一个本地优先的个人工作台。');
  await paragraph.fill('我在做本地优先的工作台，希望交流简洁、执行有清楚的范围。');
  await memory.getByRole('button',{name:'保存修改',exact:true}).click();
  await expect(memory.getByRole('button',{name:'已保存',exact:true})).toBeVisible();
  await expect(paragraph).toHaveValue('我在做本地优先的工作台，希望交流简洁、执行有清楚的范围。');
  await expect(memory.getByRole('button',{name:'来源 1',exact:true}).first()).toBeVisible();
  await expectNoHorizontalPageOverflow(page);
  await info.attach('starmate-profile.png',{body:await page.screenshot(),contentType:'image/png'});
});
